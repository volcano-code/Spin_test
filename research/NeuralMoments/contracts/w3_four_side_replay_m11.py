def compare_one_side(material,meta,plan,audit_row,*,frozen_q,design_edge,density,original_boolean_sha):
    """Reintegrate rational geometry and independent exact crossing from SAME material."""
    i=plan['index'];side=plan['side']
    require(meta.get('index')==i and meta.get('side')==side and
            meta.get('c7')==plan['c7'] and
            meta.get('native_event_sign')==plan['expected_proxy_event_sign'] and
            meta.get('native_geometry_valid') is True and
            meta.get('newton_admitted') is False and
            meta.get('agrees_with_analytic_proxy_sign') is True,
            'M11_SIDE_STATE_OR_SURROGATE_SIGN_MISMATCH')
    require(material.get('material_proof',{}).get('schema')=='cherchi-same-call-material-v1'
            and material.get('derivative_defined') is True and
            str(material.get('boolean_backend_identity','')).startswith(SOURCE_PREFIX)
            and material.get('boolean_operation') in ('intersection','subtraction')
            and material.get('quadric_source_identity'),
            'M11_NOT_A_RECORDED_PINNED_CHERCHI_MATERIAL')
    # A different exact binary hash can be *inspected*, but cannot be called
    # an identical-build result without independent SHA-equal source modules.
    if str(material['boolean_backend_identity'])!=SOURCE_PREFIX+original_boolean_sha:
        same_build=False
    else:same_build=True
    q=np.asarray(material.get('quadric_coefficients'),dtype=float)
    expected=np.asarray(frozen_q,dtype=float).copy();expected[7]=plan['c7']
    require(q.shape==(10,) and np.isfinite(q).all() and np.array_equal(q,expected),
            'M11_NEW_SIDE_CHANGES_OTHER_NATIVE_QUADRIC_COMPONENTS')
    vertices=material.get('variable_rational_vertices');faces=material.get('variable_faces')
    require(type(vertices) is list and type(faces) is list and len(vertices)>3 and len(faces)>3,
            'M11_MISSING_RATIONAL_SURFACE_BOUNDARY')
    n=check_closed_indexed_surface(faces,len(vertices))
    require(n>0 and meta.get('vertex_count')==len(vertices) and
            meta.get('face_count')==len(faces) and
            meta.get('native_feature_branch_hash')==material.get('topology_hash') and
            meta.get('native_material_geometry_hash')==material.get('geometry_hash'),
            'M11_SOURCE_BOUNDARY_IDENTITY_MISMATCH')
    require(canonical_digest({'vertices':material['material_proof']['exact_vertices'],
                              'faces':faces})==material['geometry_hash'],
            'M11_RECOMPUTED_MATERIAL_SHA_INCONSISTENT')
    require(canonical_digest({'vertices':material['quadric_source_vertices'],
                              'faces':material['quadric_source_faces'],
                              'coefficients':material['quadric_coefficients']})==material['quadric_source_identity'],
            'M11_RECOMPUTED_NATIVE_QUADRIC_SOURCE_SHA_INCONSISTENT')
    raw=np.asarray(material.get('variable_raw_moments'),dtype=float)
    recorded=np.asarray(meta.get('independent_ten_mass_moments'),dtype=float)
    jac=np.asarray(material.get('moment_jacobian'),dtype=float)
    jac_saved=np.asarray(meta.get('native_moment_jacobian_column7'),dtype=float)
    require(raw.shape==recorded.shape==(10,) and jac.shape==(10,10) and
            jac_saved.shape==(10,) and all(np.isfinite(x).all() for x in (raw,recorded,jac,jac_saved)),
            'M11_NONFINITE_OR_MISSING_R_J')
    require(np.max(np.abs(jac[:,7]-jac_saved))<=1e-12,
            'M11_J7_NOT_FROM_ACTUAL_SAME_CALL_MATERIAL')
    exact=exact_rational_ten_moments(vertices,faces,density)
    recomputed=np.asarray([float(v) for v in exact])
    error=float(np.max(np.abs(recomputed-raw)/np.maximum(1.,np.abs(raw))))
    reported_error=_real(meta.get('independent_scaled_moment_error'),
                         'M11_MISSING_RECORDED_INDEPENDENT_MOMENT_ERROR')
    source_comparison=float(np.max(np.abs(recorded-raw)/np.maximum(1.,np.abs(raw))))
    require(0<=reported_error<=1e-10 and
            abs(reported_error-source_comparison)<=1e-12,
            'M11_ARCHIVED_NUMERICAL_DISAGREEMENT_NOT_REPRODUCED')
    require(error<=1e-10 and np.max(np.abs(recomputed-recorded)/np.maximum(1.,np.abs(recorded)))<=1e-10,
            'M11_W0_INDEPENDENT_TEN_MOMENT_RECOMPUTATION_FAILED')
    source_vertices=material['quadric_source_vertices']
    require(len(source_vertices)>max(SOURCE_EDGE),'M11_MISSING_SOURCE_EDGE_VERTICES')
    sign=exact_line_witness([source_vertices[j] for j in SOURCE_EDGE],design_edge)
    require(sign['sign']==plan['expected_proxy_event_sign'] and
            audit_row.get('crossing_sign')==sign['sign'] and
            meta.get('native_event_sign')==sign['sign'],
            'M11_FOUR_SIDES_CROSSING_SIGN_NOT_INDEPENDENTLY_REPRODUCED')
    require(audit_row.get('index')==i and audit_row.get('side')==side and
            audit_row.get('c7')==plan['c7'] and
            audit_row.get('vertex_count')==len(vertices) and
            audit_row.get('face_count')==len(faces),
            'M11_INDEPENDENT_SIDE_ROW_MISMATCH')
    return {'index':i,'side':side,'c7':plan['c7'],
            'exact_moment_max_relative_scaled_error':error,
            'signed_edge_determinant_exact':sign['signed_determinant'],
            'native_and_original_boolean_binary_sha_equal':same_build,
            'oriented_closed_edge_count':n,
            'r10':raw.tolist(),'Jc_column7':jac[:,7].tolist(),
            'material_sha256_in_report':meta.get('material_sha256')}


def two_sided_derivative_diagnostics(sides):
    """Compute the two one-sided secants; mathematically finite-sample ONLY."""
    require(type(sides) is list and len(sides)==4 and
            [v.get('side') for v in sides]==list(W3_SIDES),
            'M11_WRONG_NUMERICAL_FOUR_SIDE_ORDER')
    numerical=[]
    for label,a,b in [('left',sides[0],sides[1]),('right',sides[2],sides[3])]:
        x1=_real(a['c7']);x2=_real(b['c7'])
        delta=x2-x1
        require(delta>0,'M11_INVALID_ONE_SIDE_SECANT_SPACING')
        y1=np.asarray(a['r10'],dtype=float);y2=np.asarray(b['r10'],dtype=float)
        J1=np.asarray(a['Jc_column7'],dtype=float);J2=np.asarray(b['Jc_column7'],dtype=float)
        require(all(y.shape==(10,) and np.isfinite(y).all() for y in (y1,y2,J1,J2)),
                'M11_INVALID_ONE_SIDE_JACOBIAN')
        secant=(y2-y1)/delta;meanJ=(J1+J2)/2
        err=float(np.max(np.abs(secant-meanJ)/np.maximum(1.,np.abs(meanJ))))
        numerical.append({'side':label,'secant_vs_endpoint_average_scaled_error':err,
                          'native_endpoint_J_difference_l2':float(np.linalg.norm(J2-J1)),
                          'sampling_only_not_continuity_certification':True})
    return numerical


def audit_w3_handoff(folder,original_archive,receipt):
    """Strict M11 independent review of four new *user-supplied* W3 source packets.

    Even a fully consistent receipt does not establish remote runtime identity;
    independent native execution origin, complete material partition, and an
    open differentiable stratum require stronger evidence.
    """
    folder=Path(folder)
    pins=check_external_receipt(folder,receipt)
    run,independent=check_report_and_logs(folder,pins)
    with open_pinned(original_archive,ARCHIVE_SHA256) as z:
        request=read_json(read_member(z,'artifacts/h8-request/prepared-request.json',max_bytes=10_000_000))
        base_report=read_json(read_member(z,REPORT_PREFIX+'report.json'))
        require(digest_bytes(read_member(z,REPORT_PREFIX+'report.json'))==REPORT_SHA256 and
                digest_bytes(read_member(z,'artifacts/h8-request/prepared-request.json',max_bytes=10_000_000))==REQUEST_SHA256,
                'M11_HISTORICAL_PREPARED_INPUT_SHA_MISMATCH')
    frozen_q=base_report['target_q']
    design=request['request']['design_vertices']
    design_edge=[design[k] for k in DESIGN_EDGE]
    density=request['request']['material_density']
    base_binary=base_report.get('actual_cherchi_sha256')
    require(type(base_binary) is str and HEX64.fullmatch(base_binary),'M11_ORIGINAL_H8F_BOOLEAN_SHA_MISSING')
    plan=expected_plan()
    rows=[]
    for i,side in enumerate(W3_SIDES):
        stem=f'side-{i:02d}-{side}'
        meta=_read_json_file(folder/'native'/(stem+'.json'))
        packed=folder/'native'/(stem+'.json.gz')
        require(meta.get('material_sha256')==pins['files'][f'native/{stem}.json.gz'],
                'M11_SOURCE_METADATA_NOT_BOUND_TO_RECEIPT')
        mat=read_bounded_gzip(packed)
        assert_plan=run['plan'][i]
        require(assert_plan==plan[i],'M11_W3_NATIVE_SAMPLE_PLAN_DRIFT')
        require(independent['sample_diagnostics'][i]['new_same_call_material_sha256']==
                pins['files'][f'native/{stem}.json.gz'],
                'M11_W3_INDEPENDENT_SAMPLE_DIGEST_NOT_BOUND')
        rows.append(compare_one_side(mat,meta,plan[i],independent['sample_diagnostics'][i],
                        frozen_q=frozen_q,design_edge=design_edge,density=density,
                        original_boolean_sha=base_binary))
    return {'schema':'W0_M11_W3_FOUR_REAL_SIDE_INDEPENDENT_FINITE_REVIEW_V1',
            'status':'FOUR_EXTERNAL_NATIVE_MATERIALS_STRUCTURALLY_RECHECKED_NOT_SMOOTH_CERTIFICATE',
            'original_h8f_run_conclusion':'failure',
            'original_h8f_run_id':HISTORICAL_RUN,
            'w3_head_sha_frozen_in_external_receipt':pins['frozen_w3_head_sha'],
            'w3_binary_hashes_from_source':run['binary_hashes'],
            'independent_moment_rechecks':rows,
            'one_sided_finite_difference_diagnostics':two_sided_derivative_diagnostics(rows),
            'all_new_sample_finite_checks':True,
            'runtime_origin_cryptographically_attested':False,
            'complete_native_exact_boolean_partition_certified':False,
            'continuous_derivative_neighborhood_certified':False,
            'newton_converged':False,'newton_admitted':False,'training_admissible':False}


def stage9_readiness(staged):
    """Read-only interpretation of W3 committed M9 blocker metadata."""
    require(type(staged) is dict and staged.get('schema')==
            'heart-h9-stage9-real-execution-and-source-integrity-v1' and
            staged.get('historical_run_id')==HISTORICAL_RUN and
            staged.get('historical_actions_conclusion')=='failure' and
            staged.get('historical_artifact_sha256')==ARCHIVE_SHA256 and
            staged.get('newton_admitted') is False,
            'M11_STAGE9_EVIDENCE_UNEXPECTED_OR_PROMOTED')
    n=staged.get('new_native_cherchi_calls');m=staged.get('new_native_four_point_material_archives')
    require(type(n) is int and type(m) is int and n>=0 and m>=0,
            'M11_INVALID_NATIVE_COUNTERS')
    if n<4 or m<4:
        return {'status':'BLOCKED_MISSING_FOUR_NEW_CHERCHI_SIDE_MATERIALS',
                'reason':'W3_PREVIOUS_STAGE9_HAS_NO_FOUR_NATIVE_PACKETS',
                'w3_observed_head':W3_OBSERVED_STAGE9_HEAD,
                'w3_stage9_git_blob_sha1':W3_STAGE9_PROOF_GIT_BLOB,
                'w3_new_native_calls':n,'w3_new_materials':m,
                'newton_admitted':False,'training_admissible':False}
    return {'status':'W3_REPORTS_FOUR_NATIVE_CALLS_UNVERIFIED_FILES_REQUIRED',
            'newton_admitted':False,'training_admissible':False}


