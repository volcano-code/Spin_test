def _read_limited(path: Path, max_bytes=10_000_000) -> bytes:
    require(path.is_file() and not path.is_symlink() and 0<path.stat().st_size<=max_bytes,
            'MISSING_OVERSIZED_OR_LINKED_FILE:'+path.name)
    return path.read_bytes()


def _read_json_file(path,max_bytes=10_000_000):
    try:return read_json(_read_limited(path,max_bytes))
    except (ValueError,UnicodeDecodeError,KeyError) as exc:
        raise ArchiveAuditError('INVALID_W3_JSON:'+path.name) from exc


def check_external_receipt(folder,receipt_path):
    """Reject partial, self-mutable or out-of-scope receipts before any costly replay."""
    folder=Path(folder)
    receipt=_read_json_file(Path(receipt_path),max_bytes=100_000)
    require(type(receipt) is dict and receipt.get('schema')==RECEIPT_SCHEMA,
            'M11_EXTERNAL_DIGEST_RECEIPT_SCHEMA_UNRECOGNIZED')
    require(receipt.get('historical_artifact_sha256')==ARCHIVE_SHA256 and
            isinstance(receipt.get('frozen_w3_head_sha'),str) and
            HEX40.fullmatch(receipt['frozen_w3_head_sha']) and
            receipt.get('source_verifier_git_blob')==W3_SOURCE_VERIFIER_BLOB and
            receipt.get('source_workflow_git_blob')==W3_FROZEN_WORKFLOW_BLOB,
            'M11_W3_SOURCE_AND_HISTORICAL_PROVENANCE_NOT_PINNED')
    # These binary hashes belong to the independent PRE-RUN source manifest;
    # they must not be reconstructed from the completed W3 producer report.
    pre=receipt.get('precommitted_native_binary_sha256')
    require(type(pre) is dict and set(pre)=={'core','boolean','arithmetic'} and
            all(type(v) is str and HEX64.fullmatch(v) for v in pre.values()),
            'M11_MISSING_PRE_EXECUTION_NATIVE_BINARY_IDENTITY')
    hashes=receipt.get('files')
    require(type(hashes) is dict and set(hashes)==FILES_REQUIRED and
            all(type(v) is str and HEX64.fullmatch(v) for v in hashes.values()),
            'M11_MISSING_ADDED_OR_INVALID_EXTERNAL_FILE_DIGEST')
    for name in sorted(FILES_REQUIRED):
        size_limit=32_000_000 if name.endswith('.json.gz') else 20_000_000
        value=_read_limited(folder/name,max_bytes=size_limit)
        require(digest_bytes(value)==hashes[name], 'M11_EXTERNAL_FILE_SHA256_MISMATCH:'+name)
    return receipt


def read_bounded_gzip(path,max_output_bytes=150_000_000):
    raw=_read_limited(Path(path),max_bytes=32_000_000)
    total=0
    chunks=[]
    try:
        with gzip.GzipFile(fileobj=__import__('io').BytesIO(raw)) as stream:
            while True:
                chunk=stream.read(min(1_048_576,max_output_bytes-total+1))
                if not chunk:break
                total+=len(chunk)
                require(total<=max_output_bytes,'M11_UNBOUNDED_NATIVE_GZIP_EXPANSION')
                chunks.append(chunk)
    except (OSError,EOFError,zlib.error) as exc:
        raise ArchiveAuditError('M11_CORRUPT_NATIVE_SIDE_GZIP') from exc
    require(total>0,'M11_EMPTY_GZIP')
    return read_json(b''.join(chunks))


